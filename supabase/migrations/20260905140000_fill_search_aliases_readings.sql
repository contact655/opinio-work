-- ── なぜ ──────────────────────────────────────────────────────────────────
-- 2026-09-05 に重複照合（find_companies_by_normalized_name）が
-- search_aliases も見るようにした。かな畳み（ひらがな↔カタカナ・半角カナ）は
-- 「カタカナの社名をひらがなで打った」を救うだけで、**漢字→読みは解けない**。
-- 実測: 「おおばやしぐみ」で 株式会社大林組 は **0件** だった。
--
-- ── 対象の切り分け（100社）────────────────────────────────────────────────
--   別名あり     29社 … 対象外
--   かなのみ     55社 … ★対象外（かな畳みで既に当たる。実測済み）
--   漢字を含む   14社 … ★対象（このファイル）
--   英字のみ      2社 … ★読みを特定できなかったので**空のまま**（下記）
--
-- ── ★出典 ────────────────────────────────────────────────────────────────
-- すべて **国税庁 法人番号公表サイト**（登記のフリガナ）で確認した。
--   https://www.houjin-bangou.nta.go.jp/
-- 「一般に自明だから」で入れたものは**1件も無い。**
-- 各社の照合根拠（同名の別法人と取り違えていないこと）は下の表に書いた。
--
-- ⚠️★**鹿島建設は読みが実際に割れている。**
--     カシマケンセツ  鹿島建設株式会社  青森県三戸郡南部町
--     カジマケンセツ  鹿島建設株式会社  東京都港区元赤坂１丁目３番１号  ← これ
--   うちの企業は url = https://www.kajima.co.jp/ なので**港区元赤坂の側**と判断した。
--   **次に触る人が同じ確認をしなくて済むように、ここに残す。**
--
-- ── 通称も入れる（2026-09-05 / 柴さんの判断）──────────────────────────────
-- 「おおばやし」「たけなか」と打つ人が実際にいる。ただし条件付き。
--   ・正式名の読みから**末尾の業種語**（ケンセツ / グミ / コウムテン …）を落としたものだけ
--   ・★**4文字未満の通称は入れない**（短い語ほど別会社と衝突する）
--     → 除外: カジマ(3) / シミズ(3) / ミズホ(3) / サップ(3)
--   ・★**別法人を指してしまう通称は入れない**
--     → 除外: フジフイルム（富士フイルム株式会社は別法人）
--              イトウチュウ（伊藤忠商事は別法人）
--
-- ⚠️ 投入前に総当たりで測った（詳細は下の事後チェックと同じ条件）:
--    **正規化キーが2社以上に当たる組み合わせは0件。**
--    ピッカーの ILIKE でも、追加する通称11語すべて**現状ヒット0**
--    （＝投入後もそれぞれ自社1社にしか当たらない）。
--
-- ── ★入れなかったもの ────────────────────────────────────────────────────
-- ・株式会社Third Box … 法人番号公表サイトに**0件**。URL も未登録。
--                        **特定できなかったため空。推測で入れない。**
-- ・株式会社TYU      … 同名が3件（チュウギショウジ / Ｔｙｕ・Ｔｙｕ /
--                        大分市の ティーワイユー）。**うちの TYU がどれか特定できない。**
--                        URL 未登録。**特定できなかったため空。推測で入れない。**
-- ・「ニッポン〜」   … 登記はすべて「ニホン」。登記に無い読みは入れない。
-- ・「サップ」（SAPジャパン）… ★下記
--
-- ⚠️★**SAPジャパンに「サップ」は入れなかった。** 理由は2つ:
--    ① 上の**4文字未満ルールに当たる**（サ・ッ・プ ＝ 3文字）
--    ② 登記の読みは「**エスエイピージャパン**」（千代田区大手町１丁目２番１号。
--       うちの住所と一致）。一方「**サップジャパン**」は
--       **台東区台東１丁目２７−１１の別法人**の登記読み。
--       「サップ」は**この会社の読みとして出典が無い**。
--    → 代わりに**登記の読み「エスエイピージャパン」を既存の別名に併記**した。
--
-- 法人格の読み（カブシキガイシャ等）は入れない（正規化が落とすため）。

BEGIN;

-- ── 0. 事前チェック ────────────────────────────────────────────────────────
DO $$
DECLARE v_n int;
BEGIN
  -- 対象14社が実在すること（社名が変わっていたら中止）
  SELECT count(*) INTO v_n FROM public.ow_companies WHERE name IN (
    'みずほ証券株式会社','伊藤忠テクノソリューションズ株式会社','大成建設株式会社',
    '富士フイルムビジネスイノベーションジャパン株式会社','日本オラクル株式会社',
    '日本ヒューレット・パッカード合同会社','日本マイクロソフト株式会社','株式会社大林組',
    '株式会社日本HP','株式会社竹中工務店','海光電業株式会社','清水建設株式会社',
    '高砂熱学工業株式会社','鹿島建設株式会社');
  IF v_n <> 14 THEN RAISE EXCEPTION '対象が14社でない（% 社）。中止', v_n; END IF;

  -- ⚠️ 上書きしないこと。14社とも別名が空であること
  SELECT count(*) INTO v_n FROM public.ow_companies
   WHERE name IN ('みずほ証券株式会社','伊藤忠テクノソリューションズ株式会社','大成建設株式会社',
    '富士フイルムビジネスイノベーションジャパン株式会社','日本オラクル株式会社',
    '日本ヒューレット・パッカード合同会社','日本マイクロソフト株式会社','株式会社大林組',
    '株式会社日本HP','株式会社竹中工務店','海光電業株式会社','清水建設株式会社',
    '高砂熱学工業株式会社','鹿島建設株式会社')
     AND search_aliases IS NOT NULL AND btrim(search_aliases) <> '';
  IF v_n <> 0 THEN RAISE EXCEPTION '既に別名が入っている企業が % 社ある。上書きしないので中止', v_n; END IF;

  -- SAPジャパンは既存の別名に**併記**する（消さない）
  SELECT count(*) INTO v_n FROM public.ow_companies
   WHERE name = 'SAPジャパン株式会社' AND search_aliases = 'エスエーピー';
  IF v_n <> 1 THEN RAISE EXCEPTION 'SAPジャパンの既存の別名が想定と違う。中止'; END IF;
END $$;

-- ── 1. 投入 ────────────────────────────────────────────────────────────────
--   ⚠️ 対象は社名で明示列挙する（CLAUDE.md「全社一括の UPDATE を禁止する」）。
--   ⚠️ 空白区切りの text。**配列ではない。**
UPDATE public.ow_companies AS c
   SET search_aliases = v.aliases
  FROM (VALUES
    -- 会社名                                          読み（＋通称）                  照合根拠（法人番号公表サイト）
    ('みずほ証券株式会社',
     'ミズホショウケン'),                              -- 該当1件
    ('伊藤忠テクノソリューションズ株式会社',
     'イトウチュウテクノソリューションズ'),            -- 住所一致（港区虎ノ門４丁目１番１号）
                                                       -- ⚠ 通称「イトウチュウ」は伊藤忠商事（別法人）を指すので入れない
    ('大成建設株式会社',
     'タイセイケンセツ タイセイ'),                     -- 同名4件。url=taisei.co.jp より新宿区西新宿１丁目２５番１号の1件
    ('富士フイルムビジネスイノベーションジャパン株式会社',
     'フジフイルムビジネスイノベーションジャパン'),    -- 住所一致（江東区豊洲２丁目２番１号）
                                                       -- ⚠ 通称「フジフイルム」は富士フイルム株式会社（別法人）なので入れない
    ('日本オラクル株式会社',
     'ニホンオラクル'),                                -- 住所一致（港区北青山２丁目５番８号）
    ('日本ヒューレット・パッカード合同会社',
     'ニホンヒューレットパッカード'),                  -- 住所一致（江東区大島２丁目２番１号）
    ('日本マイクロソフト株式会社',
     'ニホンマイクロソフト'),                          -- 住所一致（港区港南２丁目１６番３号 品川グランドセントラルタワー）
    ('株式会社大林組',
     'オオバヤシグミ オオバヤシ'),                     -- 同名3件だが**全て同じ読み**
    ('株式会社日本HP',
     'ニホンエイチピー'),                              -- 該当1件（港区港南１丁目２番７０号 品川シーズンテラス）
    ('株式会社竹中工務店',
     'タケナカコウムテン タケナカ'),                   -- 同名2件とも同じ読み
    ('海光電業株式会社',
     'カイコウデンギョウ カイコウ'),                   -- 住所一致（渋谷区恵比寿南１丁目１１番１５号）
    ('清水建設株式会社',
     'シミズケンセツ'),                                -- 同名4件。url=shimz.co.jp より中央区京橋２丁目１６番１号の1件
                                                       -- ⚠ 通称「シミズ」は3文字なので入れない
    ('高砂熱学工業株式会社',
     'タカサゴネツガクコウギョウ タカサゴ'),           -- 該当1件（新宿区新宿６丁目２７番３０号）
    ('鹿島建設株式会社',
     'カジマケンセツ')                                 -- ★同名で「カシマケンセツ」（青森）も実在。
                                                       --   url=kajima.co.jp より港区元赤坂１丁目３番１号の側と判断
                                                       -- ⚠ 通称「カジマ」は3文字なので入れない
  ) AS v(nm, aliases)
 WHERE c.name = v.nm;

-- SAPジャパンだけは**併記**（既存の「エスエーピー」を消さない）
--   ⚠ 登記の読みは「エスエイピージャパン」。「エスエーピー」とは
--     エー / エイ が違い、正規化では畳まれないので**両方持つ**。
UPDATE public.ow_companies
   SET search_aliases = 'エスエーピー エスエイピージャパン'
 WHERE name = 'SAPジャパン株式会社';

-- ── 2. 事後チェック ────────────────────────────────────────────────────────
DO $$
DECLARE v_n int; v_dup text;
BEGIN
  SELECT count(*) INTO v_n FROM public.ow_companies
   WHERE search_aliases IS NOT NULL AND btrim(search_aliases) <> '';
  /* 29（既存）＋ 14（今回）＝ 43。⚠️ SAPジャパンは**既存29社の中**なので足さない
     （最初 44 と書いて失敗した。トランザクションごと巻き戻っている）。 */
  IF v_n <> 43 THEN RAISE EXCEPTION '別名を持つ企業が 43 社でない（% 社）', v_n; END IF;

  -- ★「おおばやしぐみ」「かじまけんせつ」で当たること
  IF (SELECT count(*) FROM public.find_companies_by_normalized_name('おおばやしぐみ')) <> 1
  THEN RAISE EXCEPTION '「おおばやしぐみ」が1社に当たらない'; END IF;
  IF (SELECT count(*) FROM public.find_companies_by_normalized_name('かじまけんせつ')) <> 1
  THEN RAISE EXCEPTION '「かじまけんせつ」が1社に当たらない'; END IF;
  IF (SELECT count(*) FROM public.find_companies_by_normalized_name('おおばやし')) <> 1
  THEN RAISE EXCEPTION '通称「おおばやし」が1社に当たらない'; END IF;

  -- ★★過剰一致: 照合の対象になる全ての語で、2社以上に当たるものが無いこと
  SELECT string_agg(k || ' → ' || who, ' / ') INTO v_dup FROM (
    SELECT k, count(DISTINCT id) AS n, string_agg(DISTINCT nm, ' + ') AS who FROM (
      SELECT id, name AS nm, public.normalize_company_name(name) AS k FROM public.ow_companies
      UNION ALL SELECT id, name, public.normalize_company_name(brand_name) FROM public.ow_companies WHERE brand_name IS NOT NULL
      UNION ALL SELECT id, name, public.normalize_company_name(name_en)    FROM public.ow_companies WHERE name_en IS NOT NULL
      UNION ALL SELECT c.id, c.name, public.normalize_company_name(t.tok)
        FROM public.ow_companies c, regexp_split_to_table(coalesce(c.search_aliases,''), '[[:space:]　]+') AS t(tok)
       WHERE btrim(coalesce(t.tok,'')) <> ''
    ) keys WHERE k IS NOT NULL GROUP BY k HAVING count(DISTINCT id) > 1
  ) s;
  IF v_dup IS NOT NULL THEN
    RAISE EXCEPTION '2社以上に当たる語ができた: %', v_dup;
  END IF;

  RAISE NOTICE '事後チェック OK: 別名を持つ企業 % 社 / 過剰一致 0 件', v_n;
END $$;

COMMIT;
