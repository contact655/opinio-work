--    同じ学校なので、入れると一覧に同じ名前が2つ並び、同じ学校の人も分かれる。
--    例: 東京福祉大学（東京の旧コード → 群馬）・文教大学・宝塚大学・東京国際大学・大阪芸術大学短期大学部。
