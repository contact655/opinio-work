-- ⚠️ `college`（短期大学・高専）は検索・学校のページ・同じ学校の人の対象外（SEARCHABLE_SCHOOL_TYPES）。選べるようにするだけ。
-- ⚠️ 大学院は文科省データに別の行が無い（大学の中にある）。既存の「慶應義塾大学大学院」1件はそのまま。
--
-- ── 何を入れないか ──────────────────────────────────────────────────────────
-- ⚠️ `name_kana` / `logo_letter` / `logo_gradient` は入れない（高校のときと同じ。推測値を入れない。
--    既存32校の読み・ロゴの文字は**残す**＝ ① は school_code と prefecture だけを書く）。
-- ⚠️ 都道府県は都道府県番号（01〜47）で src/lib/utils/location.ts の PREFECTURES に揃えた。
--
-- ── 同じ名前のもの ──────────────────────────────────────────────────────────
-- 投入後に同じ名前・同じ種別が2件以上になる組: 0組 
--
-- ── 戻し方 ──────────────────────────────────────────────────────────────────
--   ① 投入した行を消す（既存32校は残す）:
--     delete from public.ow_schools
--      where (school_code like 'F%' or school_code like 'G%')
--        and not (type = 'university' and name in (既存32校の名前));
--   ② 既存32校の学校コードと都道府県を戻す:
--     update public.ow_schools set school_code = null, prefecture = null
--      where type = 'university' and name in (既存32校の名前);
--   ⚠️★ow_user_educations.school_id は ON DELETE SET NULL。投入後に利用者が選んだ学校を消すと、
--      **その人の学歴が学校の一覧から外れる**（学校名の文字は残る）。戻す前に参照の数を数えること。
--
