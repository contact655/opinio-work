-- | | 件数 |
-- |---|---|
-- | F1(大学) → university | 826 |
-- | F2(短大) → college | 326 |
-- | G1(高専) → college | 58 |
-- | **合計** | **1210**（うち既存の大学32校は ① で学校コードを付けるだけ・新規 1178） |
