/**
 * 氏名（姓・名・ふりがな）と電話番号の決まりごと。
 *
 * ── ⚠️★`ow_users.name` と姓名の関係 ────────────────────────────────────────
 * **`name` が「表示の正」。** `/people`・企業ページ・`/u/[id]`・フィードが読むのは今も
 * `name`（NOT NULL）で、**姓名は入力の形**でしかない。
 *
 * ⚠️★**`name` は「姓＋名」から導く派生値。必ず同じ書き込み経路で一緒に更新すること。**
 *    別経路で書くと「正と派生が食い違う」事故になる
 *    （`ow_job_roles` と `role_category_id` で実際に踏んだ形）。
 *
 * ⚠️ 既存の利用者（2026-09-14 時点で12人）は**機械で分割できない**
 *    ——氏名にスペースがあるのは7人、無いのが5人。**既存行は `name` のまま、姓名は NULL。**
 *    ＝ 姓名が空でも画面は壊れない。**`name` を消す方向の実装をしないこと。**
 */

/* ── ⚠️★ふりがなの「使い道」はまだ決まっていない（2026-09-14）──────
 * **柴さんの判断で、先に器だけ持つと決めた。**
 * ⚠️★**「読み手が無い死列」と判断して DROP しないこと。**
 *    保存（オンボーディング1画面目・必須）も表示（`/admin/candidates`）もある。
 * ⚠️★**当初書いていた「人材紹介の推薦状で使う」は誤り**（同日訂正）。
 *    OPINIO は**ダイレクトリクルーティング（募集情報等提供）**で、職業紹介ではない。
 * ⚠️ 五十音順の並び替えや検索に使うなら、**その画面を決めてから**実装すること。 */

/** 姓・名・セイ・メイ それぞれの上限。⚠️ `name` は 100 なので、その半分に収める */
export const NAME_PART_MAX = 40;

/**
 * 表示名（`ow_users.name`）を姓と名から作る。
 *
 * ⚠️ 区切りは**半角スペース1つ**。全角にしない（既存の7人が半角・全角混在なので、
 *    新しく作るぶんは1つに決める）。
 * ⚠️ 片方が空でも落ちない形にしてあるが、**呼び出し側は両方揃えてから呼ぶこと**
 *    （API は片方だけの送信を 400 で弾く）。
 */
export function buildDisplayName(familyName: string, givenName: string): string {
  return [familyName.trim(), givenName.trim()].filter(Boolean).join(" ");
}

/**
 * 表示名（`ow_users.name`）を姓と名に**分ける候補**を返す。分けられなければ `null`。
 *
 * ⚠️★★**これは「画面の初期値」を作るための関数。列へ直接書く用途に使わないこと。**
 *    CLAUDE.md の「既存の `name` から姓・名を機械的に分割しないこと」は
 *    **本人が見ないまま列に入れる**ことを禁じている。ここは本人が次の画面で
 *    目にして直せる前提なので、その禁止とは向きが違う。
 *    ⚠️ 本人の確認を挟まない経路（バックフィルの migration・API の既定値）で
 *       呼び出すなら、それは推測値の投入。**やらないこと。**
 *
 * ⚠️★**ちょうど2つに分かれるときだけ返す。** 3つ以上は姓と名の境が決まらない
 *    （「John Michael Smith」をどこで切るかは決められない）。**それらしく切らない。**
 * ⚠️ 空白なし（「木村雅樹」）も `null`。日本語は空白なしでも正しい書き方なので、
 *    **姓へ丸ごと入れない** ——「木村雅樹」が姓に入ったまま名を足すと
 *    「木村雅樹 雅樹」になり、しかも初期値が正しそうに見えるぶん気づかれにくい
 *    （2026-09-19 / 柴さんの判断）。呼び出し側は代わりに**登録名をヒントで見せる**。
 * ⚠️ `PLACEHOLDER_USER_NAME`（「ユーザー」）は人の名前ではないので `null`。
 *
 * 実測（2026-09-19 / 実ユーザー9人）: 空白あり4人（分けられる）／空白なし5人（`null`）。
 */
export function splitDisplayName(
  raw: string | null | undefined,
): { familyName: string; givenName: string } | null {
  const v = greetingName(raw);
  if (!v) return null;
  /* ⚠️ 全角スペース（\u3000）も区切りとして見る。`\s` は全角を含まない。 */
  const parts = v.split(/[\s\u3000]+/).filter(Boolean);
  if (parts.length !== 2) return null;
  return { familyName: parts[0], givenName: parts[1] };
}

/**
 * 電話番号の形式。**ゆるく見る。**
 *
 * ⚠️★**厳しくしないこと。** 国際番号・内線・ハイフンの有無で書き方が割れるので、
 *    「明らかに電話番号でないもの」だけ弾く。弾きすぎると本物を拒む。
 * ⚠️ DB に CHECK は張っていない。**3層を揃える規約は「値の集合」の制約に対するもの**で、
 *    自由入力の書式には掛けない（CLAUDE.md「適用範囲」）。
 */
export const PHONE_MAX = 20;
const PHONE_RE = /^[0-9+\-（）() 　]{9,20}$/;

export function isValidPhone(v: string): boolean {
  return PHONE_RE.test(v.trim()) && (v.match(/[0-9]/g)?.length ?? 0) >= 9;
}

/* ═══ 表示名のプレースホルダと、メールの宛名 ═══════════════════════════════ */

/**
 * 本人が名前を入れていないときに `ow_users.name` へ入る値。
 *
 * ⚠️★**同じ値を3箇所が使う。文字列で直書きしないこと。**
 *
 *   | どこ | 何をするか |
 *   |---|---|
 *   | `src/lib/auth/linkOwUser.ts` | 新規作成時の `ow_users.name`（`name?.trim() \|\| "ユーザー"`） |
 *   | **DB トリガー `handle_new_ow_user`** | 同上（`supabase/migrations/20260917090000_trigger_name_no_email.sql`） |
 *   | この定数 | メールの宛名で「名前ではない」と判定するため |
 *
 * ⚠️★**SQL 側とは共有できない**（トリガーの中にリテラルで書いてある）。
 *    **片方を変えるときは、もう片方も変えること。** 両方のコメントに同じ注意を置いてある。
 *
 * ── なぜ「名前が無ければ NULL」にしないのか ─────────────────────────────────
 * `ow_users.name` は **NOT NULL・既定値なし**。NULL を入れるとトリガーの INSERT が落ち、
 * 例外がそのまま上がって **`auth.users` の INSERT ごと失敗＝サインアップが止まる**。
 * だから「人の名前ではないが、入れておける値」が要る。
 *
 * ⚠️ **人の名前ではない。** 画面では素の名前として出る（プレースホルダと読める値であり、
 *    オンボーディング1画面目で上書きされる）が、**メールの宛名には使わない。**
 */
export const PLACEHOLDER_USER_NAME = "ユーザー";

/**
 * メールの宛名に使ってよい名前か。**使えないときは `null`。**
 *
 * ⚠️★**宛名は「行ごと出さない」で扱うこと。** 空文字を埋めて
 *    **「 さん」**や**「ユーザー さん」**を作らない。
 *    2026-09-10 に `buildScoutHtml` で決めた形を、2026-09-17 に全テンプレートへ広げた。
 *
 * ⚠️★**フォールバックの文字列をここで作らないこと**（「ご担当者」なども）。
 *    呼び出し側が「行を出すか出さないか」を決められるように、**null を返すだけ**にする。
 *
 * ⚠️★**新しいメールテンプレートを足すときは、必ずここを通すこと。**
 *    `${esc(params.userName)} さん` と素で書くと、名前が無い人に「 さん」が出る。
 */
export function greetingName(raw: string | null | undefined): string | null {
  const v = (raw ?? "").trim();
  if (!v) return null;
  if (v === PLACEHOLDER_USER_NAME) return null;
  return v;
}
