/**
 * カジュアル面談CTA の色（2026-09-06 / 柴さんの選択 = 明るい橙 + 濃い文字）。
 *
 * ── なぜ定数にしたか ────────────────────────────────────────────────────────
 * ⚠️★**同じボタンが12箇所にあり、綴りが3通りに割れていた。**
 *      `#F59E0B 0%, #FB923C 100%` ／ `#F59E0B, #F97316` ／ `#F59E0B, #D97706`
 *    色を直すたびに「1つ取り残す」形だったので、**呼び出し側で色を書かない**ことにした。
 *    `.claude/skills/ui-conventions` の「チップに個別の色を渡せる形にしないこと」と同じ理由。
 *
 * ── ★背景は明るい橙に戻し、文字を濃くした（2026-09-06）────────────────────
 * 2026-08-31 に **白文字 on #F59E0B = 2.15** を理由に背景を #C2410C まで濃くしたが、
 * 「オレンジにしたい。昔の色」という指摘を受けて**背景を戻した。**
 * ただし白文字のままでは 2.15 のままなので、**文字を白から #1C1917 に変えた。**
 *
 *   背景 #F59E0B（明るい側のストップ）× 文字 #1C1917 = **8.14** ✅
 *
 * ⚠️★**文字色を白に戻さないこと。** 戻した瞬間に 2.15 に落ちる。
 *    14px の文字に必要なのは 4.5 で、**文字を大きくしても救えない**
 *    （2.15 は 24px でも 3.0 に届かない）。だから `MEETING_CTA_FG` を用意して
 *    呼び出し側が色を書かなくて済むようにしてある。
 * ⚠️ 中間の #EA580C も白文字だと 3.56 で届かなかった（実測）。
 *
 * ⚠️ 比は**グラデーションの最も明るいストップ**で測る（そこが最悪値になる）。
 *
 * ── 橙のままである ──────────────────────────────────────────────────────────
 * ⚠️ `.claude/skills/ui-conventions`「色の役割」は**オレンジ＝カジュアル面談のみ**。
 *    **役割は変えていない。** 濃さだけを変えた。
 *
 * ⚠️ 「話を聞けます」バッジ（`components/profile/view/TalkableBadge.tsx`）は
 *    **#C2410C の文字色のまま**（#FFF7ED の上で 4.88 ✅）。
 *    あちらは薄い背景に濃い文字、こちらは濃い背景に濃い文字なので、
 *    **同じ橙系だが同じ値にはならない。** 揃えようとして片方を壊さないこと。
 *
 * ⚠️ アウトライン（白地＋橙の枠）にはしない。同じ規約が
 *    「塗り＝主要な遷移／ゴースト＝その場の展開」と定めているため。
 *
 * ⚠️ 3案の実物比較は `/dev/preview/meeting-cta`（本番では404）。
 */
export const MEETING_CTA_BG = "linear-gradient(135deg, #F59E0B 0%, #FB923C 100%)";

